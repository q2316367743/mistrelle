import { MEMORY_MAX_CHARS } from './MemoryConstant'

/**
 * 短期记忆提取提示词（反思融入）：从会话新增消息中提取值得跨会话记住的条目。
 * 输出为空标记 [NONE] 时代码层跳过写入，但仍推进提取进度，避免同一段消息被重复消费。
 */
export const MEMORY_EXTRACT_PROMPT = [
  '你是记忆提取器。从一段 AI 助手与用户的对话转写中，提取值得跨会话记住的内容。',
  '每条一行，格式：`- [类别] 内容`。类别仅限以下四种：',
  '- fact：用户的事实与背景（身份、项目、环境、约定）',
  '- preference：用户的偏好与对助手的纠正（如「包管理用 yarn 不用 npm」）',
  '- progress：项目 / 任务的进展与结论',
  '- lesson：经验教训（包括助手哪里做得不好、踩过的坑）',
  '要求：',
  '- 单条精炼成一句话，重要条目可在句尾标注日期',
  '- 最多 10 条；日常寒暄、与用户无关的中间过程、重复信息一律不记',
  '- 没有值得记住的内容时，只输出 [NONE]',
  '- 对话可能不完整，不要臆造未提及的信息'
].join('\n')

/**
 * 长期记忆合并提示词：把新增短期记忆合并进现有长期记忆，输出更新后的 MEMORY.md 全文。
 * 淘汰过时条目是有意设计——最大长度限制迫使模型遗忘低价值信息。
 */
export const MEMORY_CONSOLIDATE_PROMPT = [
  '你是记忆管理员。请把「新增的每日短期记忆」合并进「现有长期记忆」，输出更新后的长期记忆全文。',
  '规则：',
  '- 保持固定分节结构，依次为：## 用户偏好、## 事实与背景、## 进行中的事项、## 经验教训；无内容的分节可省略',
  '- 每条一行 `- 内容（YYYY-MM-DD）`；合并语义重复的条目，事实冲突时保留最新的并更新日期',
  '- 淘汰已过时、失去价值的条目（被更新替代的旧事实、已完结的事项），遗忘是特性不是缺陷',
  `- 总字数严格不超过 ${MEMORY_MAX_CHARS} 字；接近上限时优先保留 preference 与 lesson 类信息`,
  '- 直接输出 markdown 正文，不要代码块围栏、不要任何解释'
].join('\n')

