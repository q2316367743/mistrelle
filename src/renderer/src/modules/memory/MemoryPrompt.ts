import { MEMORY_SECTIONS } from './MemoryConstant'

/**
 * 短期记忆提取提示词（反思融入）：从会话新增消息中提取值得跨会话记住的条目。
 * 输出为空标记 [NONE] 时代码层跳过写入，但仍推进提取进度，避免同一段消息被重复消费。
 */
export const MEMORY_EXTRACT_PROMPT = [
  '你是记忆提取器。从一段 AI 助手与用户的对话转写中，提取值得跨会话记住的内容。',
  '每条一行，格式：`- [类别] 内容`。类别仅限以下四种：',
  '- fact：用户的事实与背景（身份、项目、环境、约定）',
  '- preference：用户的偏好与对助手的纠正（如「包管理用 yarn 不用 npm」）',
  '- progress：项目 / 任务的进展与结论',
  '- lesson：经验教训（包括助手哪里做得不好、踩过的坑）',
  '要求：',
  '- 单条精炼成一句话，重要条目可在句尾标注日期',
  '- 最多 10 条；日常寒暄、与用户无关的中间过程、重复信息一律不记',
  '- 没有值得记住的内容时，只输出 [NONE]',
  '- 对话可能不完整，不要臆造未提及的信息'
].join('\n')

/** 分节限额描述（提示词与设置页共用）：如「用户偏好 ≤800、…」 */
export const memorySectionLimitsLabel = (): string =>
  MEMORY_SECTIONS.map((s) => `${s.header.replace('## ', '')} ≤${s.budget}`).join('、')

/**
 * 长期记忆合并提示词（JSON 协议）：把新增短期记忆合并进现有长期记忆，输出结构化 JSON。
 * 淘汰过时条目是有意设计——分节字数预算迫使模型遗忘低价值信息。
 * 输出格式由代码渲染回 markdown，代码层只信任 JSON、不解析模型文本格式。
 */
export const MEMORY_CONSOLIDATE_PROMPT = [
  '你是记忆管理员。请把「新增的每日短期记忆」合并进「现有长期记忆」，输出更新后的长期记忆。',
  '只输出一个 JSON 对象，格式：',
  '{"preference": ["条目（YYYY-MM-DD）"], "fact": [...], "progress": [...], "lesson": [...]}',
  '键固定为这四类：preference（用户偏好）、fact（事实与背景）、progress（进行中的事项）、lesson（经验教训），无内容的类别给空数组。',
  '规则：',
  '- 每条目为单行字符串，句尾标注日期；合并语义重复的条目，事实冲突时保留最新的并更新日期',
  '- 淘汰已过时、失去价值的条目（被更新替代的旧事实、已完结的事项），遗忘是特性不是缺陷',
  '- 每个数组内按重要性降序排列（最重要的条目在最前）',
  `- 各数组字数上限：${memorySectionLimitsLabel()} 字；某节接近上限时只淘汰该节内过时低价值条目，禁止压缩其它类别来腾挪`,
  '- 只输出 JSON 本体，不要代码块围栏、不要任何解释'
].join('\n')

